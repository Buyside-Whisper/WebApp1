export type WarehouseType = 'main' | 'sales';
export type WarehouseStatus = 'active' | 'inactive';

export interface Warehouse {
  id: string;
  name: string;
  code: string;
  type: WarehouseType;
  branch: string | null;
  address: string;
  status: WarehouseStatus;
  managerId: string | null;
  manager: { id: string; firstName: string; lastName: string } | null;
  createdAt: string;
  updatedAt: string;
  // Computed by the backend from the products in the warehouse. Stock is split by unit.
  productCount: number;
  stockPcs: number;
  stockKg: number;
  // Sum of quantity × cost price.
  totalCost: number;
}

// The code is generated by the backend, so it's not part of the payload.
export interface WarehousePayload {
  name: string;
  type: WarehouseType;
  branch: string | null;
  address: string;
  status: WarehouseStatus;
  managerId: string | null;
}

// Any warehouse of the company, for the receipt / transfer pickers (GET /wms/warehouses/options).
// `mine`: the current user may work with it (admins: all; a manager: the ones he runs).
export type WarehouseOption = Pick<Warehouse, 'id' | 'code' | 'name' | 'type' | 'status' | 'branch'> & {
  mine: boolean;
};

// An HR employee with the manager role in WMS, offered in the Manager dropdown.
export interface ManagerOption {
  id: string;
  name: string;
}
